  END AS status,
  count(*) FILTER (WHERE vorhanden) || ' von ' || count(*) AS gefunden,
  left(string_agg(kind || ' ' || obj || CASE WHEN extra <> '' THEN '.' || extra ELSE '' END, ', ')
