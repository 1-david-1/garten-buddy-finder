  SELECT c.*,
    CASE c.kind
      WHEN 'table' THEN to_regclass('public.' || quote_ident(c.obj)) IS NOT NULL
      WHEN 'column' THEN EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = c.obj AND column_name = c.extra)
      WHEN 'function' THEN EXISTS (
        SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
        WHERE n.nspname = 'public' AND p.proname = c.obj)
      WHEN 'trigger' THEN EXISTS (
        SELECT 1 FROM pg_trigger t
        JOIN pg_class r ON r.oid = t.tgrelid
        JOIN pg_namespace n ON n.oid = r.relnamespace
        WHERE n.nspname = 'public' AND r.relname = c.obj AND t.tgname = c.extra AND NOT t.tgisinternal)
      WHEN 'policy' THEN EXISTS (
        SELECT 1 FROM pg_policies
        WHERE schemaname = 'public' AND tablename = c.obj AND policyname = c.extra)
      WHEN 'index' THEN EXISTS (
        SELECT 1 FROM pg_indexes WHERE schemaname = 'public' AND indexname = c.obj)
      ELSE false
    END AS vorhanden
  FROM checks c
)
